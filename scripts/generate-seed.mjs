import { readFileSync, writeFileSync } from 'node:fs'
import ts from 'typescript'

const source = readFileSync(new URL('../src/data/syntheticCases.ts', import.meta.url), 'utf8')
const { outputText } = ts.transpileModule(source, {
  compilerOptions: { module: ts.ModuleKind.ESNext },
})
const { syntheticCases } = await import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`)
const quote = (value) => `'${value.replaceAll("'", "''")}'`
const paragraphs = (values) => `array[${values.map(quote).join(', ')}]::text[]`
const rows = syntheticCases.map((item) =>
  `(${[item.id, item.title, item.context].map(quote).join(', ')}, ${paragraphs(item.humanFeedback)}, ${paragraphs(item.aiFeedback)}, ${quote(item.revealNote)}, ${quote(item.discussionPrompt)}, true)`,
)
writeFileSync(new URL('../supabase/seed.sql', import.meta.url),
  `-- Generated by node scripts/generate-seed.mjs. Fictional cases only.\n-- Existing cases and all votes are preserved; review before running against a hosted project.\nbegin;\ninsert into prebi_private.cases\n(id, title, context, human_feedback, ai_feedback, reveal_note, discussion_prompt, active)\nvalues\n${rows.join(',\n')}\non conflict (id) do nothing;\ncommit;\n`)
